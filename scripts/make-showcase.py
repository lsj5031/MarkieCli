#!/usr/bin/env python3
"""Create captioned feature clips from verified stories and real renderer outputs.

Usage: python scripts/make-showcase.py MANIFEST.json OUTPUT_DIR
Development dependencies: Pillow, imageio-ffmpeg. No product runtime dependency.
The manifest contains a list of {id, title, description, image, command} objects;
image paths are relative to the repository root. Build current native binaries,
execute each workflow with its output redirected to the manifest image directory,
and rasterize PDF previews before encoding. Captions are not a live recording.
"""

import csv
import json
import math
from pathlib import Path
import re
import shlex
import subprocess
import sys
import textwrap

from PIL import Image, ImageDraw, ImageFont
import imageio_ffmpeg


ROOT = Path(__file__).resolve().parents[1]
WIDTH, HEIGHT, FPS = 1920, 1080, 24
BG = (10, 17, 29)
PANEL = (18, 29, 45)
INK = (235, 241, 247)
MUTED = (158, 177, 195)
ACCENT = (113, 225, 196)
FONT_DIR = Path("/usr/share/fonts/truetype/dejavu")


def font(size, bold=False, mono=False):
    name = "DejaVuSansMono" if mono else "DejaVuSans"
    if bold:
        name += "-Bold"
    return ImageFont.truetype(str(FONT_DIR / (name + ".ttf")), size)


def lines(draw, text, xy, max_width, face, color=INK, gap=12):
    x, y = xy
    for paragraph in text.splitlines():
        words = paragraph.split()
        current = ""
        for word in words:
            candidate = (current + " " + word).strip()
            if current and draw.textlength(candidate, font=face) > max_width:
                draw.text((x, y), current, font=face, fill=color)
                y += face.size + gap
                current = word
            else:
                current = candidate
        draw.text((x, y), current, font=face, fill=color)
        y += face.size + gap
    return y


def base():
    canvas = Image.new("RGB", (WIDTH, HEIGHT), BG)
    draw = ImageDraw.Draw(canvas)
    draw.rounded_rectangle((72, 54, 110, 92), radius=10, fill=ACCENT)
    draw.text((126, 53), "MARKIE", font=font(30, True), fill=INK)
    draw.text((WIDTH - 411, 60), "NATIVE MARKDOWN RENDERER", font=font(17), fill=MUTED)
    draw.line((72, 123, WIDTH - 72, 123), fill=(37, 55, 73), width=2)
    return canvas


def title_card(title, subtitle, footer):
    canvas = base()
    draw = ImageDraw.Draw(canvas)
    draw.text((100, 270), "NATIVE RUST RENDERING", font=font(22, True), fill=ACCENT)
    y = lines(draw, title, (92, 330), 1660, font(88, True), gap=18)
    lines(draw, subtitle, (100, y + 38), 1550, font(31), color=MUTED, gap=15)
    draw.rounded_rectangle((100, 850, 750, 914), radius=16, fill=PANEL)
    draw.text((126, 865), "SVG     /     PNG     /     PDF", font=font(25, True), fill=ACCENT)
    draw.text((100, 986), footer, font=font(19), fill=MUTED)
    return canvas


def feature_canvas(item, index, total):
    canvas = base()
    draw = ImageDraw.Draw(canvas)
    draw.text((76, 159), f"{index:02d} / {total:02d}    VERIFIED WORKFLOW", font=font(19, True), fill=ACCENT)
    y = lines(draw, item["title"], (72, 209), 1710, font(56, True), gap=5)
    lines(draw, item["description"], (76, y + 12), 1720, font(26), color=MUTED, gap=8)
    draw.rounded_rectangle((72, 382, 677, 941), radius=22, fill=PANEL)
    for x, color in [(100, (237, 111, 109)), (127, (230, 193, 108)), (154, ACCENT)]:
        draw.ellipse((x, 407, x + 13, 420), fill=color)
    draw.text((100, 463), "COMMAND", font=font(19, True), fill=ACCENT)
    wrapped = "\n".join(textwrap.wrap(item["command"], 39, break_long_words=False, break_on_hyphens=False))
    lines(draw, wrapped, (100, 506), 547, font(23, mono=True), color=INK, gap=10)
    draw.text((100, 823), "Real output. Reproducible input.", font=font(20), fill=MUTED)
    draw.text((100, 865), f"STORY  {item['id']}", font=font(21, True), fill=ACCENT)
    draw.rounded_rectangle((710, 382, 1848, 941), radius=22, fill=(30, 44, 61))
    draw.text((76, 984), "Commands shown are verified workflows; product outputs are generated by Markie.", font=font(18), fill=MUTED)
    return canvas


def frame_stream(still, seconds, output, image=None, pan=True):
    ffmpeg = imageio_ffmpeg.get_ffmpeg_exe()
    args = [ffmpeg, "-y", "-loglevel", "error", "-f", "rawvideo", "-pix_fmt", "rgb24",
            "-s", f"{WIDTH}x{HEIGHT}", "-r", str(FPS), "-i", "-", "-an", "-c:v", "libx264",
            "-preset", "veryfast", "-crf", "19", "-pix_fmt", "yuv420p", "-movflags", "+faststart", str(output)]
    background = Image.new("RGB", (WIDTH, HEIGHT), BG)
    frames = int(seconds * FPS)
    scaled = None
    if image is not None:
        image = image.convert("RGB")
        # Documents pan at readable width; diagrams retain their full context.
        fit_width = 1086 if pan else min(1086, round(image.width * 505 / image.height))
        fit_height = round(image.height * fit_width / image.width)
        scaled = image.resize((fit_width, fit_height), Image.Resampling.LANCZOS)
    with subprocess.Popen(args, stdin=subprocess.PIPE) as process:
        try:
            for number in range(frames):
                progress = number / max(1, frames - 1)
                frame = still.copy()
                if scaled is not None:
                    eased = (1 - math.cos(progress * math.pi)) / 2
                    offset = round(max(0, scaled.height - 505) * eased)
                    crop = scaled.crop((0, offset, scaled.width, min(scaled.height, offset + 505)))
                    frame.paste(crop, (736 + (1086 - crop.width) // 2, 409 + (505 - crop.height) // 2))
                draw = ImageDraw.Draw(frame)
                draw.rounded_rectangle((72, 1036, 1848, 1040), radius=2, fill=(34, 53, 69))
                draw.rounded_rectangle((72, 1036, 72 + max(2, round(1776 * progress)), 1040), radius=2, fill=ACCENT)
                fade = min(1.0, number / 12, (frames - 1 - number) / 12)
                if fade < 1:
                    frame = Image.blend(background, frame, fade)
                process.stdin.write(frame.tobytes())
        finally:
            process.stdin.close()
        if process.wait() != 0:
            raise RuntimeError(f"Video encoding failed: {output}")


def main():
    manifest = Path(sys.argv[1])
    output = Path(sys.argv[2])
    output.mkdir(parents=True, exist_ok=True)
    items = json.loads(manifest.read_text())
    with (ROOT / "docs/feature-audit.csv").open(newline="") as stream:
        stories = {row["id"]: row for row in csv.DictReader(stream)}
    for item in items:
        row = stories[item["id"]]
        latest_retest = row["retest"].splitlines()[-1].split("] ", 1)[-1] if row["retest"] else ""
        if row["status"] != "passed" or not re.match(r"^passed(?:\b|:)", latest_retest, re.I):
            raise ValueError(f"Showcase story has not passed post-fix validation: {item['id']}")
    subprocess.run(["cargo", "build", "--bins", "--lib"], cwd=ROOT, check=True)
    metadata = subprocess.run(["cargo", "metadata", "--no-deps", "--format-version", "1"], cwd=ROOT, check=True, capture_output=True, text=True)
    binaries = Path(json.loads(metadata.stdout)["target_directory"]) / "debug"
    logs = []
    for item in items:
        image_path = ROOT / item["image"]
        image_path.parent.mkdir(parents=True, exist_ok=True)
        command = shlex.split(item["command"])
        command[0] = str(binaries / command[0])
        destination_index = command.index("-o") + 1
        destination = image_path.with_name(Path(command[destination_index]).name)
        command[destination_index] = str(destination)
        destination.unlink(missing_ok=True)
        result = subprocess.run(command, cwd=ROOT, check=True, capture_output=True, text=True)
        logs.append({"id": item["id"], "command": command, "stdout": result.stdout, "stderr": result.stderr})
        if destination.suffix.lower() == ".pdf":
            image_path.unlink(missing_ok=True)
            subprocess.run(["pdftoppm", "-singlefile", "-scale-to", "1500", "-png", str(destination), str(image_path.with_suffix(""))], check=True)
        if not image_path.is_file():
            raise ValueError(f"Workflow produced no image: {item['id']}")
    (output / "commands.json").write_text(json.dumps(logs, indent=2) + "\n")
    intro = title_card("Markdown.\nRendered natively.", "Documents, diagrams and mathematics — ready to share.", "A feature tour built from tested workflows and actual product output.")
    intro.save(output / "cover.png")
    paths = []
    path = output / "00-intro.mp4"
    frame_stream(intro, 5, path)
    paths.append(path)
    thumbnails = []
    for index, item in enumerate(items, 1):
        still = feature_canvas(item, index, len(items))
        image = Image.open(ROOT / item["image"])
        preview = still.copy()
        preview_image = image.convert("RGB")
        preview_image.thumbnail((1086, 505), Image.Resampling.LANCZOS)
        preview.paste(preview_image, (736 + (1086 - preview_image.width) // 2, 409 + (505 - preview_image.height) // 2))
        preview.save(output / f"{index:02d}-{item['id']}.png")
        thumbnails.append(preview)
        path = output / f"{index:02d}-{item['id']}.mp4"
        frame_stream(still, 10, path, image=image, pan=shlex.split(item["command"])[0] != "markie-mermaid")
        paths.append(path)
        print(f"Created {path}", flush=True)
    outro = title_card("Your document.\nOne command.", "Native Rust · Themeable output · No JavaScript runtime", "Requires usable system fonts or ./fonts. Reproducible inputs and evidence accompany this tour.")
    path = output / "99-outro.mp4"
    frame_stream(outro, 5, path)
    paths.append(path)
    playlist = output / "playlist.txt"
    playlist.write_text("\n".join("file '" + str(path.resolve()).replace("'", "'\\''") + "'" for path in paths))
    subprocess.run([imageio_ffmpeg.get_ffmpeg_exe(), "-y", "-loglevel", "error", "-f", "concat", "-safe", "0", "-i", str(playlist), "-c", "copy", "-movflags", "+faststart", str(output / "markie-product-tour.mp4")], check=True)
    playlist.unlink()
    sheet = Image.new("RGB", (960 * 2, 540 * ((len(thumbnails) + 1) // 2)), BG)
    for index, thumbnail in enumerate(thumbnails):
        sheet.paste(thumbnail.resize((960, 540)), ((index % 2) * 960, (index // 2) * 540))
    sheet.save(output / "storyboard.png")
    print(f"Created {output / 'markie-product-tour.mp4'}", flush=True)


if __name__ == "__main__":
    main()
